import '../models/indoor_venue.dart';

/// Demo indoor maps linked to outdoor Ability Map places.
final seedIndoorVenues = <IndoorVenue>[
  _cityHospital,
  _grandMall,
];

IndoorVenue? indoorVenueForPlace(String placeId) {
  for (final v in seedIndoorVenues) {
    if (v.placeId == placeId || v.id == placeId) return v;
  }
  return null;
}

